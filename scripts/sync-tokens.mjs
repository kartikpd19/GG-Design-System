#!/usr/bin/env node
/**
 * Sync Figma variables → @goodgame/style.
 *
 * Sources (first one available wins):
 *   1. Figma REST API  — set FIGMA_TOKEN (and optionally FIGMA_FILE_KEY).
 *      Note: GET /v1/files/:key/variables/local requires a Figma Enterprise plan.
 *   2. Local export    — scripts/figma-variables.json, same shape as the REST
 *      response (`{ meta: { variables, variableCollections } }`), e.g. from a
 *      "variables export" plugin.
 *
 * Usage:
 *   yarn sync-tokens            report differences between Figma and packages/style
 *   yarn sync-tokens --write    also write packages/style/src/tokens/generated/figma-variables.css
 */
import { readFile, readdir, writeFile, mkdir } from "node:fs/promises";
import { existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const tokensDir = join(root, "packages/style/src/tokens");
const localExport = join(root, "scripts/figma-variables.json");
const fileKey = process.env.FIGMA_FILE_KEY ?? "2C5ebJzU146r07jIOPVQxk";
const write = process.argv.includes("--write");

async function loadVariables() {
  if (process.env.FIGMA_TOKEN) {
    const res = await fetch(`https://api.figma.com/v1/files/${fileKey}/variables/local`, {
      headers: { "X-Figma-Token": process.env.FIGMA_TOKEN },
    });
    if (!res.ok) throw new Error(`Figma API ${res.status}: ${await res.text()}`);
    return (await res.json()).meta;
  }
  if (existsSync(localExport)) {
    return JSON.parse(await readFile(localExport, "utf8")).meta;
  }
  throw new Error(
    "No source found. Set FIGMA_TOKEN (Enterprise plan) or add scripts/figma-variables.json.",
  );
}

// "Colors/primary-color" or "--primary-color" → "primary-color"
const toCssName = (name) => name.split("/").pop().trim().replace(/^--/, "").toLowerCase();

const channel = (n) => Math.round(n * 255);
function colorToCss({ r, g, b, a = 1 }) {
  if (a < 1) return `rgba(${channel(r)}, ${channel(g)}, ${channel(b)}, ${+a.toFixed(2)})`;
  return `#${[r, g, b].map((n) => channel(n).toString(16).padStart(2, "0")).join("")}`;
}

function resolveValue(variable, modeId, byId, depth = 0) {
  const value = variable.valuesByMode[modeId] ?? Object.values(variable.valuesByMode)[0];
  if (value?.type === "VARIABLE_ALIAS") {
    const target = byId[value.id];
    if (!target || depth > 10) return undefined;
    return resolveValue(target, Object.keys(target.valuesByMode)[0], byId, depth + 1);
  }
  if (variable.resolvedType === "COLOR") return colorToCss(value);
  if (variable.resolvedType === "FLOAT") return `${value}px`;
  return String(value);
}

/** Map of css var name → value for each Figma mode (lower-cased mode name). */
function collectFigmaTokens(meta) {
  const byId = meta.variables;
  const modes = {};
  for (const collection of Object.values(meta.variableCollections)) {
    for (const mode of collection.modes) {
      const key = mode.name.toLowerCase();
      modes[key] ??= {};
      for (const id of collection.variableIds) {
        const variable = byId[id];
        if (!variable || variable.hiddenFromPublishing) continue;
        if (!["COLOR", "FLOAT"].includes(variable.resolvedType)) continue;
        const value = resolveValue(variable, mode.modeId, byId);
        if (value !== undefined) modes[key][toCssName(variable.name)] = value;
      }
    }
  }
  return modes;
}

/** Literal (non-var()) values currently declared in packages/style. */
async function collectCodeTokens() {
  const tokens = {};
  for (const file of await readdir(tokensDir)) {
    if (!file.endsWith(".css")) continue;
    const css = await readFile(join(tokensDir, file), "utf8");
    for (const [, name, value] of css.matchAll(/--([\w-]+):\s*([^;]+);/g)) {
      tokens[name] = value.trim().toLowerCase();
    }
  }
  return tokens;
}

const meta = await loadVariables();
const figma = collectFigmaTokens(meta);
const code = await collectCodeTokens();
const light = figma.light ?? figma["mode 1"] ?? Object.values(figma)[0] ?? {};

let differences = 0;
for (const [name, value] of Object.entries(light)) {
  const current = code[name];
  if (current === undefined) {
    console.log(`+ --${name}: ${value}  (in Figma, missing in code)`);
    differences++;
  } else if (!current.startsWith("var(") && current !== value.toLowerCase()) {
    console.log(`~ --${name}: code ${current} ≠ figma ${value}`);
    differences++;
  }
}
console.log(differences ? `\n${differences} difference(s) found.` : "Tokens are in sync.");

if (write) {
  const outDir = join(tokensDir, "generated");
  await mkdir(outDir, { recursive: true });
  const block = (selector, vars) =>
    `${selector} {\n${Object.entries(vars)
      .map(([n, v]) => `  --${n}: ${v};`)
      .join("\n")}\n}\n`;
  let css = "/* Generated by scripts/sync-tokens.mjs — do not edit by hand. */\n\n";
  css += block(":root", light);
  if (figma.dark) css += `\n${block('[data-theme="dark"]', figma.dark)}`;
  await writeFile(join(outDir, "figma-variables.css"), css);
  console.log("Wrote packages/style/src/tokens/generated/figma-variables.css");
}
